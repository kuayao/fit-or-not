const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.PROTOTYPE_URL || 'http://127.0.0.1:8765/prototype/';
const root = path.resolve(__dirname, '..');
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROME_EXECUTABLE, headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, deviceScaleFactor: 1 });
  const errors = [];
  const httpFailures = [];
  const checks = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('response', response => { if (response.status() >= 400) httpFailures.push(`${response.status()} ${response.url()}`); });
  const open = async screen => { await page.goto(`${base}index.html?embed=1&screen=${screen}`); };
  const go = async screen => { await page.evaluate(screen => navigate(screen), screen); };
  const click = async action => { await page.locator(`[data-action="${action}"]`).first().click(); };
  const confirm = async (name, expression) => { assert.equal(await page.evaluate(expression), true, name); checks.push(name); };
  await open('wardrobe');
  const names = await page.evaluate(() => screens.map(screen => screen[0]));
  const layoutCases = [];
  for (const width of [320, 375, 390, 430]) {
    await page.setViewportSize({ width, height: 844 });
    for (const name of names) {
      await open(name);
      await page.locator('#app img').evaluateAll(images => Promise.all(images.map(img => img.decode())));
      const result = await page.evaluate(({width, name}) => ({ width, name, documentOverflow: document.documentElement.scrollWidth > width, appOverflow: app.scrollWidth > app.clientWidth + 1, brokenImages: [...document.images].filter(img => !img.complete || !img.naturalWidth).length }), {width, name});
      assert.equal(result.documentOverflow || result.appOverflow || !!result.brokenImages, false, JSON.stringify(result));
      layoutCases.push(result);
    }
  }
  await page.setViewportSize({width: 390, height: 844});
  await open('wardrobe');
  await page.locator('#wardrobe-search').fill('针织');
  await confirm('搜索名称筛选为两件针织衣物', () => document.querySelectorAll('.clothing-card').length === 2);
  await page.locator('#wardrobe-search').fill('');
  await page.locator('[data-action="category"][data-value="下装"]').click();
  await confirm('分类筛选为三件下装', () => document.querySelectorAll('.clothing-card').length === 3);
  await page.locator('[data-action="category"][data-value="全部"]').click();
  await click('favorite');
  await confirm('收藏操作更新状态', () => state.clothes[0].favorite === false);
  await click('filter'); await click('toggle-favorites'); await click('apply-filter');
  await confirm('只看收藏筛选', () => document.querySelectorAll('.clothing-card').length === 3);
  await page.evaluate(() => actions['clear-filters']());
  await click('new-clothing');
  await page.locator('#clothing-form button[type="submit"]').click();
  await confirm('未选分类不能保存', () => document.getElementById('form-error').textContent.includes('请选择'));
  await page.locator('#clothing-name').fill('测试衣物');
  await page.locator('#clothing-category').selectOption('上装');
  await page.locator('#price').fill('0');
  await page.locator('#clothing-form button[type="submit"]').click();
  await confirm('添加衣物保留零元价格', () => state.clothes[0].name === '测试衣物' && state.clothes[0].price === 0);
  await page.locator('[data-action="clothing"][data-id="c1"]').click();
  await click('clothing-more'); await click('delete-clothing');
  await confirm('有引用衣物阻止永久删除', () => document.querySelector('[role="dialog"]').textContent.includes('还有记录') && !!findClothing('c1'));
  await click('archive-clothing');
  await confirm('归档保留历史引用', () => findClothing('c1').archived && state.records[0].items.includes('c1') && !activeClothes().some(item => item.id === 'c1'));
  await open('outfit-edit');
  const box = await page.locator('[data-canvas-id="c1"]').boundingBox();
  const originalX = await page.evaluate(() => state.canvasLayout.c1.x);
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 + 20, box.y + box.height / 2 + 15); await page.mouse.up();
  assert.notEqual(await page.evaluate(() => state.canvasLayout.c1.x), originalX); checks.push('真实指针拖动修改画布位置');
  await click('canvas-rotate');
  await confirm('旋转操作', () => state.canvasLayout.c1.rotation === 15);
  await click('canvas-undo');
  await confirm('撤销旋转', () => state.canvasLayout.c1.rotation === 0);
  await page.locator('[data-action="canvas-scale"][data-factor="1.12"]').click();
  await confirm('缩放保持包围盒比例', () => Math.abs(state.canvasLayout.c1.w / state.canvasLayout.c1.h - .5 / .54) < .00001);
  const layout = await page.evaluate(() => JSON.stringify(state.canvasLayout));
  await page.locator('#outfit-name').fill('保存布局测试');
  await click('save-outfit'); await click('edit-outfit');
  assert.equal(await page.evaluate(() => JSON.stringify(state.canvasLayout)), layout); checks.push('保存后重新打开布局一致');
  await open('calendar');
  await click('new-record');
  await page.locator('#wear-note').fill('同日第二条');
  await page.locator('#wear-form button[type="submit"]').click();
  await confirm('同日多条记录穿着次数去重', () => state.records.filter(r => r.date === today).length === 2 && wearCount('c1') === 3);
  await page.locator('[data-action="day"][data-date="2026-11-06"]').click();
  await click('edit-record');
  await confirm('历史快照展示实际单品', () => document.querySelector('.outfit-cover').querySelectorAll('img').length === 3 && state.wearItems.join(',') === 'c1,c8,c9');
  await go('outfit-detail'); await click('record-outfit');
  await confirm('新记录不沿用上次编辑的历史单品', () => state.wearItems === null && document.querySelector('.outfit-cover').querySelectorAll('img').length === 4);
  await go('calendar');
  await page.locator('[data-action="day"][data-date="2026-11-13"]').click();
  await click('new-record');
  await confirm('禁止登记未来实际穿着', () => state.screen === 'calendar' && document.getElementById('toast').textContent.includes('过去'));
  await open('packing-detail');
  await click('packed');
  await confirm('清单勾选更新', () => state.packingLists[0].packed.length === 1);
  await click('packing-copy');
  await confirm('复制清单重置打包状态', () => state.packingLists.length === 2 && state.packingLists[1].packed.length === 0 && state.packingLists[1].items.length === 5);
  await click('packing-add'); await page.locator('[data-action="packing-pick"][data-id="c1"]').click();
  await confirm('清单重复衣物去重', () => state.packingLists[1].items.length === 5);
  await open('jobs'); await click('run-job');
  await page.waitForFunction(() => state.jobState === 'succeeded');
  checks.push('模拟图片任务等待到成功');
  await click('job-fail');
  await confirm('模拟任务失败可见', () => app.textContent.includes('再试一次'));
  await click('run-job'); await click('job-cancel');
  await page.waitForTimeout(1300);
  await confirm('模拟取消不被延迟成功覆盖', () => state.jobState === 'cancelled');
  await open('try-on');
  await confirm('未同意前禁用试穿生成', () => document.querySelector('[data-action="generate-try-on"]').disabled);
  await page.locator('#try-consent').check(); await click('generate-try-on');
  await confirm('同意后展示试穿示意', () => state.tryOnReady);
  await open('settings'); await click('toggle-services'); await go('recommendations');
  await confirm('服务未配置不可发起推荐', () => !document.querySelector('[data-action="generate-ai"]'));
  await open('welcome'); await click('login');
  await page.locator('#invite-code').fill('DEMO'); await click('redeem-invite');
  await confirm('演示准入进入衣橱', () => state.screen === 'wardrobe');
  await open('settings');
  const downloadPromise = page.waitForEvent('download'); await click('export-data');
  const download = await downloadPromise;
  const exported = JSON.parse(fs.readFileSync(await download.path(), 'utf8'));
  assert.equal(exported.clothes.length, 12); checks.push('本地JSON导出有效');
  await page.setViewportSize({width: 1440, height: 1100});
  await page.goto(`${base}index.html`);
  for (const mode of ['empty','error','loading','normal']) {
    await page.locator('#demo-state').selectOption(mode);
    await confirm(`衣橱${mode}状态切换`, () => state.screen === 'wardrobe' && app.textContent.length > 0);
  }
  for (const [name,file] of names.map(name => [name, name === 'outfit-edit' ? 'outfit-editor' : name])) {
    await page.setViewportSize({width: 390, height: 844}); await open(name);
    await page.locator('#app img').evaluateAll(images => Promise.all(images.map(img => img.decode())));
    await page.screenshot({path: path.join(root, 'previews', `${file}.png`)});
  }
  await page.setViewportSize({width: 1800, height: 1100});
  await page.goto(`${base}board.html`);
  for (const frame of page.frames()) await frame.locator('img').evaluateAll(images => Promise.all(images.map(img => img.decode())));
  await page.screenshot({path: path.join(root, 'previews/design-board.png'), fullPage: true});
  assert.deepEqual(errors, []); assert.deepEqual(httpFailures, []);
  const report = {date: new Date().toISOString(), browser: await browser.version(), viewportWidths:[320,375,390,430], pages: names.length, layoutCases: layoutCases.length, interactions: checks, pageErrors: errors, httpFailures, result:'passed', scope:'仅HTML设计原型；不包含微信、后端、PG、模型和外部服务验证'};
  fs.writeFileSync(path.join(__dirname, 'prototype-results.json'), JSON.stringify(report, null, 2)+'\n');
  console.log(JSON.stringify(report, null, 2));
  await browser.close();
})();
